from __future__ import annotations

import os
from pathlib import Path

import pytest

from codewhy.config import Config
from codewhy.pipeline import run_pipeline
from codewhy.project import build_project
from codewhy.render.docs_tree import OutputError, render_docs_tree, write_outputs
from tests.helpers import FIXED_TIME
from tests.support.fake_provider import FakeProvider
from tests.test_render_single_file import GOLDEN, VERSION, check_golden, headings, scripted_run

FIXTURES = Path(__file__).parent / "fixtures"


def parse_frontmatter(text: str) -> dict[str, str]:
    assert text.startswith("---\n"), "missing frontmatter"
    block, _rest = text[4:].split("\n---\n", 1)
    return dict(line.split(": ", 1) for line in block.split("\n"))


def tree_for(fixture: str = "flat_scripts") -> dict[str, str]:
    config = Config()
    project = build_project(FIXTURES / fixture, config)
    run = run_pipeline(project, FakeProvider(), config, clock=lambda: FIXED_TIME, use_cache=False)
    return render_docs_tree(project, run, config, version=VERSION)


def write_tree(root: Path, tree: dict[str, str]) -> None:
    write_outputs(root, {f"codewhy-docs/{key}": value for key, value in tree.items()}, output_dir="codewhy-docs")


def test_tree_matches_goldens() -> None:
    project, run, config = scripted_run()
    tree = render_docs_tree(project, run, config, version=VERSION)
    assert sorted(tree) == ["PROJECT_OVERVIEW.md", "_module.md", "main.py.md", "solver.py.md", "utils.py.md"]
    for name, text in tree.items():
        check_golden(f"flat_scripts_tree/{name}", text)
    if not os.environ.get("CODEWHY_UPDATE_GOLDEN"):
        assert sorted(p.name for p in (GOLDEN / "flat_scripts_tree").iterdir()) == sorted(tree)


def test_tree_headings_are_shifted_up_one_level() -> None:
    project, run, config = scripted_run()
    tree = render_docs_tree(project, run, config, version=VERSION)
    assert headings(tree["solver.py.md"])[:2] == ["# `solver.py`", "## Purpose"]
    assert headings(tree["_module.md"])[:2] == ["# `(project root)`", "## Responsibility"]
    assert headings(tree["PROJECT_OVERVIEW.md"])[:2] == ["# flat_scripts", "## Overview"]
    assert "## Notes" in tree["solver.py.md"]  # docs-tree is always Level 0


def test_tree_mirrors_nested_sources_with_root_module() -> None:
    tree = tree_for("nested_modules")
    project = build_project(FIXTURES / "nested_modules", Config())
    expected = {"PROJECT_OVERVIEW.md"}
    expected |= {"_module.md" if m.path == "." else f"{m.path}/_module.md" for m in project.modules}
    expected |= {f"{path}.md" for path in project.structures}
    assert set(tree) == expected
    assert "src/app/api/_module.md" in tree and "src/app/api/routes.py.md" in tree


def test_every_tree_file_has_parseable_frontmatter_with_its_source() -> None:
    for name, text in tree_for("nested_modules").items():
        meta = parse_frontmatter(text)
        assert meta["generated_by"].startswith("codewhy v")
        assert meta["generated_at"] == "2026-01-01T12:00:00Z"
        if name == "PROJECT_OVERVIEW.md":
            assert meta["source"] == "project"
        elif name.endswith("_module.md"):
            assert meta["source"] == (name.removesuffix("_module.md").rstrip("/") or ".")
        else:
            assert meta["source"] == name.removesuffix(".md")
        assert text.endswith("\n") and not text.endswith("\n\n")


def test_default_tree_dir_is_codewhy_docs() -> None:
    assert Config().output.dir == "codewhy-docs"


def test_handwritten_target_is_refused_without_partial_write(tmp_path: Path) -> None:
    tree = tree_for()
    (tmp_path / "PROJECT_DOCS.md").write_text("mine\n", encoding="utf-8")
    with pytest.raises(OutputError, match="not generated by codewhy"):
        write_outputs(tmp_path, {"PROJECT_DOCS.md": "generated\n", "other.md": tree["PROJECT_OVERVIEW.md"]})
    assert not (tmp_path / "other.md").exists()
    assert (tmp_path / "PROJECT_DOCS.md").read_text(encoding="utf-8") == "mine\n"


def test_stale_cleanup_only_removes_codewhy_documents(tmp_path: Path) -> None:
    tree_dir = tmp_path / "codewhy-docs"
    (tree_dir / "gone").mkdir(parents=True)
    (tree_dir / "deleted.py.md").write_text("---\ngenerated_by: codewhy vtest\n---\nold\n", encoding="utf-8")
    (tree_dir / "gone" / "_module.md").write_text("---\ngenerated_by: codewhy vtest\n---\nold\n", encoding="utf-8")
    (tree_dir / "handwritten.md").write_text("mine\n", encoding="utf-8")
    (tree_dir / "mentions.md").write_text("notes about generated_by: codewhy\n", encoding="utf-8")
    write_tree(tmp_path, tree_for())
    assert not (tree_dir / "deleted.py.md").exists()
    assert not (tree_dir / "gone" / "_module.md").exists()
    assert (tree_dir / "handwritten.md").read_text(encoding="utf-8") == "mine\n"
    assert (tree_dir / "mentions.md").exists()


def symlink_or_skip(link: Path, target: Path, *, directory: bool) -> None:
    try:
        link.symlink_to(target, target_is_directory=directory)
    except (OSError, NotImplementedError) as exc:
        pytest.skip(f"symlinks unavailable here: {exc}")


def test_cleanup_never_follows_symlinks(tmp_path: Path) -> None:
    root = tmp_path / "project"
    outside = tmp_path / "outside"
    outside.mkdir()
    victim = outside / "old.py.md"
    victim.write_text("---\ngenerated_by: codewhy vtest\n---\nold\n", encoding="utf-8")
    (root / "codewhy-docs").mkdir(parents=True)
    symlink_or_skip(root / "codewhy-docs" / "linked", outside, directory=True)
    symlink_or_skip(root / "codewhy-docs" / "link.py.md", victim, directory=False)
    write_tree(root, tree_for())
    assert victim.exists()
    assert (root / "codewhy-docs" / "link.py.md").is_symlink()


def test_writing_through_a_symlinked_output_dir_is_refused(tmp_path: Path) -> None:
    root = tmp_path / "project"
    root.mkdir()
    outside = tmp_path / "outside"
    outside.mkdir()
    symlink_or_skip(root / "codewhy-docs", outside, directory=True)
    with pytest.raises(OutputError, match="symlink"):
        write_tree(root, tree_for())
    assert list(outside.iterdir()) == []


def test_output_traversal_is_rejected(tmp_path: Path) -> None:
    with pytest.raises(OutputError):
        write_outputs(tmp_path, {"../outside.md": "bad\n"})
    assert not (tmp_path.parent / "outside.md").exists()
