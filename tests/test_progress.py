"""Progress, warnings and the summary line (task 08 §8 `test_progress.py`)."""

from __future__ import annotations

import io
from pathlib import Path

import pytest
from rich.console import Console

import codewhy.cli as cli
from codewhy.llm.provider import TransientError
from codewhy.progress import ProgressReporter, item_line, summary_line, terminal_text
from tests.helpers import make_project, run_cli
from tests.support.fake_provider import FakeProvider

PROJECT = {
    "main.py": "from helpers import load\n\nload()\n",
    "helpers.py": "SECRET = 'must never be printed'\n\n\ndef load():\n    return SECRET\n",
}


def install(monkeypatch: pytest.MonkeyPatch, fake: FakeProvider) -> FakeProvider:
    monkeypatch.setattr(cli, "build_provider", lambda config: fake)
    return fake


def test_item_lines_for_generated_cached_and_failed(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    make_project(tmp_path, PROJECT)
    # Path order: helpers.py is call 0 and fails; main.py, module ".", project succeed.
    install(monkeypatch, FakeProvider(errors={0: TransientError("down")}))
    first = run_cli(["scan", str(tmp_path)])
    assert first.exit_code == 2
    assert first.stdout.splitlines()[:4] == [
        "[1/4] file  helpers.py  (failed)",
        "[2/4] file  main.py  (generated)",
        "[3/4] module  .  (generated)",
        f"[4/4] project  {tmp_path.name}  (generated)",
    ]
    assert first.stdout.splitlines()[-1].startswith("2 files, 0 cached, 3 generated, 1 failed, 0 skipped.")

    install(monkeypatch, FakeProvider())
    second = run_cli(["scan", str(tmp_path)])
    assert second.exit_code == 0, second.stderr
    lines = second.stdout.splitlines()
    assert lines[:2] == ["[1/4] file  helpers.py  (generated)", "[2/4] file  main.py  (cached)"]
    # helpers.py now has a real Purpose, so the module (and FakeProvider's project text) re-run.
    assert lines[-1].startswith("2 files, 1 cached, 3 generated, 0 failed, 0 skipped. PROJECT_DOCS.md ≈ ")


def test_plain_output_is_items_then_summary_without_stage_lines_or_source(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    make_project(tmp_path, PROJECT)
    install(monkeypatch, FakeProvider())
    result = run_cli(["scan", str(tmp_path)])
    assert result.exit_code == 0, result.stderr
    lines = result.stdout.splitlines()
    assert all(line.startswith("[") for line in lines[:-1]) and len(lines) == 5
    assert "must never be printed" not in result.stdout + result.stderr
    for noise in ("discovery:", "request", "checking provider", "\x1b"):
        assert noise not in result.stdout


def test_quiet_keeps_the_summary_and_errors(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    make_project(tmp_path, PROJECT)
    install(monkeypatch, FakeProvider())
    quiet = run_cli(["scan", str(tmp_path), "--quiet"])
    assert quiet.exit_code == 0
    assert quiet.stdout.splitlines() == [quiet.stdout.strip()]
    assert quiet.stdout.startswith("2 files, 0 cached, 4 generated")
    (tmp_path / "PROJECT_DOCS.md").write_text("hand written\n", encoding="utf-8")
    refused = run_cli(["scan", str(tmp_path), "--quiet"])
    assert refused.exit_code == 1 and "was not generated by codewhy" in refused.stderr


def test_skip_lines_and_warnings_come_after_items_and_before_the_summary(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    make_project(tmp_path, {**PROJECT, "broken.py": "def broken(:\n", ".codewhy/cache.db": b"not a database" * 50})
    install(monkeypatch, FakeProvider())
    result = run_cli(["scan", str(tmp_path)])
    assert result.exit_code == 2
    lines = result.stdout.splitlines()
    skip = lines.index("skipped broken.py (SyntaxError: invalid syntax (line 1))")
    assert all(line.startswith("[") for line in lines[:skip]) and skip == len(lines) - 2
    assert lines[-1].startswith("3 files, 0 cached, 4 generated, 0 failed, 1 skipped.")
    assert result.stderr.splitlines() == ["warning: cache unreadable, rebuilding"]


def test_ascii_fallback_for_terminal_output_only(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    assert terminal_text("a — b → c … ≈ 9", "ascii") == "a - b -> c ... ~ 9"
    assert terminal_text("ünïcode", "ascii") == "?n?code"
    assert terminal_text("a — b", "utf-8") == "a — b"
    make_project(tmp_path, PROJECT)
    install(monkeypatch, FakeProvider())
    monkeypatch.setattr(cli, "stream_encoding", lambda stream: "ascii")
    result = run_cli(["scan", str(tmp_path)])
    assert result.exit_code == 0, result.stderr
    assert " PROJECT_DOCS.md ~ " in result.stdout and "≈" not in result.stdout
    assert "codebase documentation" in (tmp_path / "PROJECT_DOCS.md").read_text(encoding="utf-8")
    assert "—" in (tmp_path / "PROJECT_DOCS.md").read_text(encoding="utf-8")  # the file stays UTF-8


def test_tty_reporter_prints_items_with_a_spinner() -> None:
    buffer = io.StringIO()
    console = Console(file=buffer, force_terminal=True, width=100)
    reporter = ProgressReporter(quiet=False, echo=lambda line: None, console=console, project_label="demo")
    reporter.set_total(2)
    reporter.start("checking provider…")
    reporter.on_stage("file request a.py", "started: attempt 1/2")
    reporter.on_item("file", "a.py", "generated")
    reporter.on_item("project", "", "cached")
    reporter.stop()
    text = buffer.getvalue()
    assert "[1/2] file  a.py  (generated)" in text and "[2/2] project  demo  (cached)" in text


def test_quiet_reporter_prints_nothing() -> None:
    printed: list[str] = []
    reporter = ProgressReporter(quiet=True, echo=printed.append, console=None)
    reporter.set_total(1)
    reporter.start("x")
    reporter.on_item("file", "a.py", "generated")
    assert printed == [] and reporter.index == 1


def test_line_formats() -> None:
    assert item_line(7, 18, "file", "src/solver.py", "generated") == "[7/18] file  src/solver.py  (generated)"
    counts = {"generated": 7, "cached": 11, "failed": 0}
    assert summary_line(18, counts, 1, "PROJECT_DOCS.md", 9400, 0) == (
        "18 files, 11 cached, 7 generated, 0 failed, 1 skipped. PROJECT_DOCS.md ≈ 9,400 tokens (level 0)."
    )
    assert summary_line(1, {}, 0, None, None, 0).endswith("docs-tree output written (level 0).")
