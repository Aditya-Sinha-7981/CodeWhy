"""Docs-tree rendering and Task 6 output safety boundary."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Iterable, Mapping

from codewhy.config import Config
from codewhy.pipeline import RunResult
from codewhy.project import ProjectModel

from .writer import write_atomic
from .sections import frontmatter, file_section, module_section, project_overview_sections

CODEWHY_MARKER = "generated_by: codewhy"


class OutputError(Exception):
    """An output target cannot be safely written or cleaned."""


def _normalize(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n") + "\n"


def _source_time(run: RunResult, kind: str, path: str | None = None):
    if kind == "project":
        return run.project.generated_at
    result = run.modules[path] if kind == "module" else run.files[path]
    return result.generated_at


def render_docs_tree(project: ProjectModel, run_result: RunResult, config: Config, *, version: str) -> dict[str, str]:
    """Return Level 0 docs-tree documents keyed by paths relative to output dir."""
    output: dict[str, str] = {}
    overview = [
        frontmatter(version=version, source="project", generated_at=_source_time(run_result, "project")),
        "",
        f"# {project.name}",
        "",
            project_overview_sections(project, run_result),
    ]
    output["PROJECT_OVERVIEW.md"] = _normalize("\n".join(overview))
    for module in project.modules:
        relative = "_module.md" if module.path == "." else f"{module.path}/_module.md"
        content = [
            frontmatter(version=version, source=module.path, generated_at=_source_time(run_result, "module", module.path)),
            "",
            module_section(project, run_result, module, heading_offset=-2),
        ]
        output[relative] = _normalize("\n".join(content))
    for path in sorted(run_result.files):
        content = [
            frontmatter(version=version, source=path, generated_at=_source_time(run_result, "file", path)),
            "",
            file_section(project, run_result, path, heading_offset=-2),
        ]
        output[f"{path}.md"] = _normalize("\n".join(content))
    return dict(sorted(output.items()))


def _inside(root: Path, candidate: Path) -> bool:
    try:
        candidate.relative_to(root)
    except ValueError:
        return False
    return True


def _target(root: Path, relative: str) -> Path:
    if Path(relative).is_absolute() or "\\" in relative or any(part == ".." for part in Path(relative).parts):
        raise OutputError(f"output path escapes the scanned folder: {relative}")
    candidate = (root / Path(*relative.split("/"))).absolute()
    if not _inside(root, candidate):
        raise OutputError(f"output path escapes the scanned folder: {relative}")
    current = candidate
    while current != root:
        if current.is_symlink():
            raise OutputError(f"refusing to follow symlink in output path: {current}")
        current = current.parent
    return candidate


def _is_codewhy(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8", newline="") as handle:
            first = handle.read(512).replace("\r\n", "\n").replace("\r", "\n")
    except (OSError, UnicodeError):
        return False
    return first.startswith("---\n") and CODEWHY_MARKER in first.split("---\n", 2)[1] if first.startswith("---\n") else False


def validate_output_targets(root: Path, targets: Mapping[str, str], *, force: bool = False) -> dict[str, Path]:
    """Validate all output targets before any write and return absolute targets."""
    resolved_root = root.resolve()
    result: dict[str, Path] = {}
    for relative in sorted(targets):
        path = _target(resolved_root, relative)
        current = path
        while current != resolved_root:
            if current.is_symlink():
                raise OutputError(f"refusing to write through symlink: {current}")
            current = current.parent
        if path.exists() and path.is_symlink():
            raise OutputError(f"refusing to write through symlink: {path}")
        if path.exists() and not force and not _is_codewhy(path):
            raise OutputError(f"output exists and was not generated by codewhy: {path} (use --force to overwrite)")
        result[relative] = path
    return result


def _stale_targets(root: Path, output_dir: Path, current: set[str]) -> list[Path]:
    stale: list[Path] = []
    if not output_dir.is_dir() or output_dir.is_symlink():
        return stale
    for base, dirs, files in os.walk(output_dir, topdown=True, followlinks=False):
        dirs[:] = [name for name in dirs if not (Path(base) / name).is_symlink()]
        for name in files:
            candidate = Path(base) / name
            if candidate.is_symlink() or not _is_codewhy(candidate):
                continue
            relative = candidate.relative_to(output_dir).as_posix()
            if relative not in current:
                stale.append(candidate)
    return sorted(stale)


def _check_writable(root: Path, paths: Iterable[Path]) -> None:
    """Refuse before the first write when a target folder cannot be written (avoids a partial set).

    Best effort: `os.access` can be optimistic (e.g. Windows ACLs); the write itself still reports errors.
    """
    for folder in sorted({path.parent for path in paths}):
        existing = folder
        while not existing.exists() and existing != root:
            existing = existing.parent
        if not os.access(existing, os.W_OK):
            raise OutputError(f"cannot write to {existing}: permission denied")


def write_outputs(root: Path, targets: Mapping[str, str], *, output_dir: str | None = None, force: bool = False) -> None:
    """Validate and write generated targets, then remove safe stale tree docs."""
    resolved_root = root.resolve()
    absolute = validate_output_targets(resolved_root, targets, force=force)
    _check_writable(resolved_root, absolute.values())
    for relative, path in absolute.items():
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            write_atomic(path, _normalize(targets[relative]))
        except OSError as exc:
            raise OutputError(f"cannot write {path}: {exc.strerror or exc}") from None
    if output_dir is not None:
        directory = _target(resolved_root, output_dir)
        prefix = output_dir.rstrip("/") + "/"
        current = {name.removeprefix(prefix) for name in targets if name.startswith(prefix)}
        for stale in _stale_targets(resolved_root, directory, current):
            try:
                stale.unlink()
            except OSError as exc:
                raise OutputError(f"cannot remove stale generated file {stale}: {exc.strerror or exc}") from None
